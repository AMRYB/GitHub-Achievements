export function getAchievementById(id: string): Achievement | undefined {
  return achievements.find((a) => a.id === id);
}

export function getAchievementsByCategory(category: string): Achievement[] {
  if (category === 'all') return achievements;
  return achievements.filter((a) => a.category === category);
}

export function getEarnableAchievements(): Achievement[] {
  return achievements.filter((a) => a.isEarnable && !a.isLegacy);
}

export function getAutoEarnableAchievements(): Achievement[] {
  return achievements.filter((a) => a.canAutoEarn);
}
